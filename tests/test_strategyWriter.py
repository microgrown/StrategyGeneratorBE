DELIMITER = "------------------------------"


class Item:
    """Stands in for mainGUI.RuleItem (duck-typed by the writer)."""

    def __init__(self, name, flipped=False, negated=False, params=None):
        self.name = name
        self.flipped = flipped
        self.negated = negated
        self.params = params or {}


class Pane:
    """Stands in for mainGUI.RulePane."""

    def __init__(self, ruleType, items):
        self.ruleType = ruleType
        self.items = items


MOMENTUM = Rule(
    name="Momentum",
    type="Entry",
    inputVariables={"Length": "20"},
    longCondition="close[0] > close[Length]",
    shortCondition="close[0] < close[Length]",
)

STOP_LOSS = Rule(
    name="StopLoss",
    type="Exit",
    inputVariables={"stopLoss": "1000"},
    longCondition="ctx.OpenPositionProfit() < -stopLoss",
    shortCondition="ctx.OpenPositionProfit() < -stopLoss",
)

MONTHLY_TARGET = Rule(
    name="MonthlyTarget",
    type="Switch",
    inputVariables={"target": "5000"},
    localVariables={
        "monthProfit": {"type": "double", "init": "0.0"},
        "ii": {"type": "int", "init": "0"},
    },
    classMembersHook="double Half(double x) const { return x / 2.0; }",
    startOfFileHook="if (ctx.CurrentBar() == 1) { monthProfit = 0.0; }",
    preConditionHook="monthProfit += ctx.OpenPositionProfit();",
    longCondition="monthProfit > target",
    shortCondition="monthProfit > target",
    endOfFileHook="ii = ii + 1;",
)

RULES = {r.name: r for r in (MOMENTUM, STOP_LOSS, MONTHLY_TARGET)}


def getRule(name):
    return RULES[name]


def build(strategyName, panes):
    return sw.buildHeaderText(strategyName, panes, getRule=getRule)


def readText(path):
    with open(path) as f:
        return f.read()


def momentumPane(params=None):
    return Pane("Entry", [Item("Momentum", params=params)])


# The full expected header for one entry + one exit + one switch. Golden text:
# every change to the emitter must be a deliberate edit here.
GOLDEN = '''#pragma once

// Momentum Clone
// Auto-generated by StrategyGeneratorBE. Do not edit by hand.

#include "bt/sim/strategy.h"

#ifdef _MSC_VER
#pragma warning(push)
#pragma warning(disable: 4100 4101 4189 4244 4456)
#endif

namespace bt {

// "Momentum Clone V1": entries Momentum; exits StopLoss; switches MonthlyTarget
class Gen_Momentum_Clone_V1 : public Strategy {
public:
    Gen_Momentum_Clone_V1()
        : E1_Length_h_(DeclareInput("E1_Length", 5, 50, 5)),
          X1_stopLoss_h_(DeclareInput("X1_stopLoss", 1000, 1000, 0)),
          S1_target_h_(DeclareInput("S1_target", 5000, 5000, 0)) {}

    void OnBarClose(Context& ctx) override {
        const auto& open = ctx.open;
        const auto& high = ctx.high;
        const auto& low = ctx.low;
        const auto& close = ctx.close;
        const auto& volume = ctx.volume;

        const double E1_Length = Input(E1_Length_h_);
        const double X1_stopLoss = Input(X1_stopLoss_h_);
        const double S1_target = Input(S1_target_h_);

        bool enterLong = true, enterShort = true;
        bool exitLong = false, exitShort = false;

        // -- Start of bar --
        if (ctx.CurrentBar() == 1) { S1_monthProfit = 0.0; }

        // -- Entries --
        enterLong = enterLong && (close[0] > close[E1_Length]);
        enterShort = enterShort && (close[0] < close[E1_Length]);

        // -- Exits --
        exitLong = exitLong || (ctx.OpenPositionProfit() < -X1_stopLoss);
        exitShort = exitShort || (ctx.OpenPositionProfit() < -X1_stopLoss);

        // -- Switches --
        S1_monthProfit += ctx.OpenPositionProfit();
        enterLong = enterLong && !(S1_monthProfit > S1_target);
        enterShort = enterShort && !(S1_monthProfit > S1_target);
        exitLong = exitLong || (S1_monthProfit > S1_target);
        exitShort = exitShort || (S1_monthProfit > S1_target);

        // -- Order placement --
        if (enterLong && ctx.MarketPosition() <= 0) ctx.EnterLong(1);
        if (enterShort && ctx.MarketPosition() >= 0) ctx.EnterShort(1);
        if (exitLong && ctx.MarketPosition() > 0) ctx.Exit();
        if (exitShort && ctx.MarketPosition() < 0) ctx.Exit();

        // -- End of bar --
        S1_ii = S1_ii + 1;
    }

private:
    double Half(double x) const { return x / 2.0; }

    std::size_t E1_Length_h_;
    std::size_t X1_stopLoss_h_;
    std::size_t S1_target_h_;
    double S1_monthProfit = 0.0;
    int S1_ii = 0;
};

}  // namespace bt

#ifdef _MSC_VER
#pragma warning(pop)
#endif
'''


class TestGoldenHeader(unittest.TestCase):
    def testFullHeaderForOneOfEachRoleMatches(self):
        panes = [
            momentumPane({"Length": {"start": "5", "stop": "50", "step": "5"}}),
            Pane("Exit", [Item("StopLoss")]),
            Pane("Switch", [Item("MonthlyTarget")]),
        ]
        text, entries = build("Momentum Clone", panes)
        self.assertEqual(text, GOLDEN)
        self.assertEqual(entries, [("Momentum Clone V1", "Gen_Momentum_Clone_V1")])


class TestSanitizeIdentifier(unittest.TestCase):
    def testSpacesAndPunctuationBecomeUnderscores(self):
        self.assertEqual(sw.sanitizeIdentifier("Momentum Clone"), "Momentum_Clone")
        self.assertEqual(sw.sanitizeIdentifier("A - B (2)"), "A_B_2")

    def testEdgeUnderscoresAreStripped(self):
        self.assertEqual(sw.sanitizeIdentifier(" Momentum "), "Momentum")

    def testLeadingDigitIsPrefixed(self):
        self.assertEqual(sw.sanitizeIdentifier("2Fast"), "S_2Fast")

    def testEmptyResultIsPrefixed(self):
        self.assertEqual(sw.sanitizeIdentifier("---"), "S_")

    def testKeywordIsRejected(self):
        with self.assertRaises(GenerationError):
            sw.sanitizeIdentifier("class")

    def testDerivedNames(self):
        self.assertEqual(sw.headerFileName("Momentum Clone"), "gen_momentum_clone.h")
        self.assertEqual(sw.className("Momentum Clone", 2), "Gen_Momentum_Clone_V2")
        self.assertEqual(sw.registryName("Momentum Clone", 2), "Momentum Clone V2")
        self.assertEqual(sw.specStem("Momentum Clone", 2), "momentum_clone_v2")


class TestRenameVars(unittest.TestCase):
    def testWholeWordOnly(self):
        self.assertEqual(
            sw._renameVars("Length + LengthTwo + xLength", {"Length": "1"}, "E1_"),
            "E1_Length + LengthTwo + xLength",
        )

    def testCaseSensitive(self):
        # The TS original matched case-insensitively because EL is; C++ is not,
        # so "close" must not be captured by a rule variable named "Close".
        self.assertEqual(
            sw._renameVars("close[0] > Close", {"Close": "1"}, "E1_"),
            "close[0] > E1_Close",
        )

    def testLongestNameFirst(self):
        text = sw._renameVars("len + lenTwo", {"len": "1", "lenTwo": "2"}, "E1_")
        self.assertEqual(text, "E1_len + E1_lenTwo")

    def testInputsAndLocalsShareTheNamespace(self):
        rule = Rule(
            name="R",
            inputVariables={"n": "1"},
            localVariables={"acc": {"type": "double", "init": "0"}},
            longCondition="acc > n",
        )
        text, _ = sw.buildHeaderText(
            "S", [Pane("Entry", [Item("R")])], getRule=lambda name: rule
        )
        self.assertIn("enterLong = enterLong && (E1_acc > E1_n);", text)


class TestFlipAndNegate(unittest.TestCase):
    def _conditions(self, **itemKwargs):
        text, _ = build("S", [Pane("Entry", [Item("Momentum", **itemKwargs)])])
        return text

    def testPlain(self):
        text = self._conditions()
        self.assertIn("enterLong = enterLong && (close[0] > close[E1_Length]);", text)

    def testFlipSwapsLongAndShort(self):
        text = self._conditions(flipped=True)
        self.assertIn("enterLong = enterLong && (close[0] < close[E1_Length]);", text)
        self.assertIn("enterShort = enterShort && (close[0] > close[E1_Length]);", text)

    def testNegateWrapsInNot(self):
        text = self._conditions(negated=True)
        self.assertIn(
            "enterLong = enterLong && (!( close[0] > close[E1_Length] ));", text
        )

    def testFlipThenNegate(self):
        text = self._conditions(flipped=True, negated=True)
        self.assertIn(
            "enterLong = enterLong && (!( close[0] < close[E1_Length] ));", text
        )


