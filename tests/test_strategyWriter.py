class TestInputDeclarations(unittest.TestCase):
    def _decl(self, params):
        text, _ = build("S", [momentumPane(params)])
        for line in text.splitlines():
            if "DeclareInput" in line:
                return line.strip()
        return ""

    def testFullRangeIsUsed(self):
        self.assertIn(
            'DeclareInput("E1_Length", 5, 50, 5)',
            self._decl({"Length": {"start": "5", "stop": "50", "step": "5"}}),
        )

    def testNoParamsFallsBackToTheRuleDefault(self):
        self.assertIn('DeclareInput("E1_Length", 20, 20, 0)', self._decl(None))

    def testStartOnlyPinsTheInput(self):
        self.assertIn(
            'DeclareInput("E1_Length", 30, 30, 0)',
            self._decl({"Length": {"start": "30", "stop": "", "step": ""}}),
        )

    def testStopEqualToStartPinsTheInput(self):
        # grid.cpp returns 1 iteration for stop == start before it checks step.
        self.assertIn(
            'DeclareInput("E1_Length", 30, 30, 0)',
            self._decl({"Length": {"start": "30", "stop": "30", "step": "5"}}),
        )

    def testBlankStepPinsTheInput(self):
        self.assertIn(
            'DeclareInput("E1_Length", 5, 5, 0)',
            self._decl({"Length": {"start": "5", "stop": "50", "step": ""}}),
        )

    def testIndivisibleSpanIsRejected(self):
        with self.assertRaises(GenerationError) as cm:
            self._decl({"Length": {"start": "5", "stop": "50", "step": "7"}})
        self.assertIn("Length", str(cm.exception))
        self.assertIn("Momentum", str(cm.exception))

    def testStopBelowStartIsRejected(self):
        with self.assertRaises(GenerationError):
            self._decl({"Length": {"start": "50", "stop": "5", "step": "5"}})


class TestVersionEnumeration(unittest.TestCase):
    def testDelimiterSplitsAPaneIntoVersions(self):
        pane = Pane("Entry", [Item("Momentum"), DELIMITER, Item("Momentum")])
        text, entries = build("Multi", [pane])
        self.assertEqual(
            entries,
            [("Multi V1", "Gen_Multi_V1"), ("Multi V2", "Gen_Multi_V2")],
        )
        self.assertIn("class Gen_Multi_V1 : public Strategy {", text)
        self.assertIn("class Gen_Multi_V2 : public Strategy {", text)

    def testVersionsAreTheCrossProductOfPanes(self):
        panes = [
            Pane("Entry", [Item("Momentum"), DELIMITER, Item("Momentum")]),
            Pane("Exit", [Item("StopLoss"), DELIMITER, Item("StopLoss")]),
        ]
        _, entries = build("Multi", panes)
        self.assertEqual(len(entries), 4)

    def testEmptyGroupIsAValidVersion(self):
        pane = Pane("Entry", [Item("Momentum"), DELIMITER])
        _, entries = build("Multi", [pane])
        self.assertEqual(len(entries), 2)

    def testPrefixesRestartInEachVersion(self):
        pane = Pane("Entry", [Item("Momentum"), DELIMITER, Item("Momentum")])
        text, _ = build("Multi", [pane])
        # Per-version classes mean no V-part is needed to stay unique.
        self.assertEqual(text.count('DeclareInput("E1_Length"'), 2)

    def testNoPanesIsAnError(self):
        with self.assertRaises(GenerationError):
            build("Multi", [])

    def testOccurrencePrefixesCountUpWithinARole(self):
        pane = Pane("Entry", [Item("Momentum"), Item("Momentum")])
        text, _ = build("Multi", [pane])
        self.assertIn('DeclareInput("E1_Length"', text)
        self.assertIn('DeclareInput("E2_Length"', text)


class TestManifestAndIncFiles(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.dir = self._tmp.name
        self.addCleanup(self._tmp.cleanup)

    def _batch(self, header, entries):
        return {"header": header, "entries": [{"name": n, "class": c} for n, c in entries]}

    def _touch(self, name):
        with open(os.path.join(self.dir, name), "w") as f:
            f.write("// header\n")

    def testIncFilesListEveryBatch(self):
        manifest = {
            "Alpha": self._batch("gen_alpha.h", [("Alpha V1", "Gen_Alpha_V1")]),
            "Beta": self._batch("gen_beta.h", [("Beta V1", "Gen_Beta_V1")]),
        }
        self._touch("gen_alpha.h")
        self._touch("gen_beta.h")
        with open(sw.manifestPath(self.dir), "w") as f:
            json.dump(manifest, f)

        headersPath, registryPath = sw.rebuildIncFiles(self.dir)
        headers = readText(headersPath)
        registry = readText(registryPath)

        self.assertIn('#include "bt/strategies/generated/gen_alpha.h"', headers)
        self.assertIn('#include "bt/strategies/generated/gen_beta.h"', headers)
        self.assertIn(
            '{"Alpha V1", [] { return std::make_unique<Gen_Alpha_V1>(); }},', registry
        )
        # Every entry line must be comma-terminated: it lands inside a braced
        # initializer in registry.cpp.
        for line in registry.splitlines():
            if not line.startswith("//"):
                self.assertTrue(line.endswith(","), line)

    def testBatchWithAMissingHeaderIsPruned(self):
        manifest = {
            "Alpha": self._batch("gen_alpha.h", [("Alpha V1", "Gen_Alpha_V1")]),
            "Gone": self._batch("gen_gone.h", [("Gone V1", "Gen_Gone_V1")]),
        }
        self._touch("gen_alpha.h")
        with open(sw.manifestPath(self.dir), "w") as f:
            json.dump(manifest, f)

        headersPath, registryPath = sw.rebuildIncFiles(self.dir)
        self.assertNotIn("gen_gone.h", readText(headersPath))
        self.assertNotIn("Gone V1", readText(registryPath))
        self.assertNotIn("Gone", sw.loadManifest(self.dir))

    def testEmptyManifestWritesCommentOnlyFiles(self):
        headersPath, registryPath = sw.rebuildIncFiles(self.dir)
        for path in (headersPath, registryPath):
            for line in readText(path).splitlines():
                self.assertTrue(line.startswith("//"), line)

    def testDuplicateRegistryNameAcrossBatchesIsRejected(self):
        manifest = {
            "Alpha": self._batch("gen_alpha.h", [("Shared V1", "Gen_Alpha_V1")]),
            "Beta": self._batch("gen_beta.h", [("Shared V1", "Gen_Beta_V1")]),
        }
        self._touch("gen_alpha.h")
        self._touch("gen_beta.h")
        with open(sw.manifestPath(self.dir), "w") as f:
            json.dump(manifest, f)
        with self.assertRaises(GenerationError) as cm:
            sw.rebuildIncFiles(self.dir)
        self.assertIn("Shared V1", str(cm.exception))

    def testTwoStrategiesSharingAHeaderNameIsRejected(self):
        manifest = {
            "Momentum Clone": self._batch("gen_momentum_clone.h", [("A V1", "Gen_A_V1")]),
            "Momentum-Clone": self._batch("gen_momentum_clone.h", [("B V1", "Gen_B_V1")]),
        }
        self._touch("gen_momentum_clone.h")
        with open(sw.manifestPath(self.dir), "w") as f:
            json.dump(manifest, f)
        with self.assertRaises(GenerationError) as cm:
            sw.rebuildIncFiles(self.dir)
        self.assertIn("gen_momentum_clone.h", str(cm.exception))

    def testMissingManifestIsAnEmptyOne(self):
        self.assertEqual(sw.loadManifest(self.dir), {})

    def testCorruptManifestIsAnEmptyOne(self):
        with open(sw.manifestPath(self.dir), "w") as f:
            f.write("{ not json")
        self.assertEqual(sw.loadManifest(self.dir), {})


class TestGenerate(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.engineDir = self._tmp.name
        self.addCleanup(self._tmp.cleanup)
        self.cfg = {
            "engineDir": self.engineDir,
            "generatedSubdir": "src/bt/strategies/generated",
        }
        patcher = mock.patch.object(ruleIO, "loadRule", side_effect=getRule)
        patcher.start()
        self.addCleanup(patcher.stop)

    def generatedDir(self):
        return os.path.join(
            self.engineDir, "src", "bt", "strategies", "generated"
        )

    def testWritesHeaderManifestAndIncFiles(self):
        result = sw.generate("Momentum Clone", [momentumPane()], self.cfg)

        self.assertTrue(os.path.exists(result.headerPath))
        self.assertEqual(os.path.basename(result.headerPath), "gen_momentum_clone.h")
        self.assertEqual(result.versionCount, 1)
        self.assertEqual(
            result.entries, [("Momentum Clone V1", "Gen_Momentum_Clone_V1")]
        )

        manifest = sw.loadManifest(self.generatedDir())
        self.assertEqual(manifest["Momentum Clone"]["header"], "gen_momentum_clone.h")
        self.assertIn(
            "Momentum Clone V1", readText(result.registryIncPath)
        )
        self.assertIn("gen_momentum_clone.h", readText(result.headersIncPath))

    def testRegeneratingReplacesTheStrategysOwnBatch(self):
        pane = Pane("Entry", [Item("Momentum"), DELIMITER, Item("Momentum")])
        sw.generate("Momentum Clone", [pane], self.cfg)
        result = sw.generate("Momentum Clone", [momentumPane()], self.cfg)

        registry = readText(result.registryIncPath)
        self.assertIn("Momentum Clone V1", registry)
        self.assertNotIn("Momentum Clone V2", registry)

    def testASecondStrategyCoexists(self):
        sw.generate("Alpha", [momentumPane()], self.cfg)
        result = sw.generate("Beta", [momentumPane()], self.cfg)

        registry = readText(result.registryIncPath)
        self.assertIn("Alpha V1", registry)
        self.assertIn("Beta V1", registry)
        headers = readText(result.headersIncPath)
        self.assertIn("gen_alpha.h", headers)
        self.assertIn("gen_beta.h", headers)

    def testBadParameterRangeLeavesTheEngineTreeUntouched(self):
        pane = momentumPane({"Length": {"start": "5", "stop": "50", "step": "7"}})
        with self.assertRaises(GenerationError):
            sw.generate("Momentum Clone", [pane], self.cfg)
        self.assertFalse(os.path.exists(self.generatedDir()))

    def testBlankNameIsRejected(self):
        with self.assertRaises(GenerationError):
            sw.generate("  ", [momentumPane()], self.cfg)

    def testIllegalFilenameCharIsRejected(self):
        with self.assertRaises(GenerationError):
            sw.generate("Momentum/Clone", [momentumPane()], self.cfg)

    def testMissingEngineDirIsRejected(self):
        with self.assertRaises(GenerationError):
            sw.generate("Momentum Clone", [momentumPane()], {"engineDir": ""})


